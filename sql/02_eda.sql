-- 1. Сколько строк и за какой период?
select count(*)        as rows_cnt,
       min(created_at) as first_order,
       max(created_at) as last_order
from raw.orders;
-- Результат: 77 243 строки, с 2026-05-01 по 2026-09-01
-- Вывод: период не совпадает с заявленным в ТЗ (май–август), есть данные за сентябрь


-- 2. Что является ключом? Уникален ли order_id?
select count(order_id)          as order_id_cnt,
       count(DISTINCT order_id) as unique_order_id_cnt
from raw.orders;
-- Результат: 77 243 order_id, 77 243 уникальных order_id
-- Вывод: order_id уникален, дубликатов нет


-- 3. Какие значения в status и platform, сколько каждого?
select DISTINCT platform as unique_platform_values
from raw.orders;
select DISTINCT status as unique_status_values
from raw.orders;
-- Вывод: платформы web, ios, android, статусы cancelled и delivered



